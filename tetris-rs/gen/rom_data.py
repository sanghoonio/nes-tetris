#!/usr/bin/env python3
"""Write tetris-rs/src/rom_data.rs: the PRG address ranges the reimplementation reads.

Everything in PRG that the disassembly doesn't mark as an instruction (tables, screen layouts,
music, the inline data after `jsr bulkCopyToPpu`), less the segments it marks unreferenced,
plus the few instruction bytes the game reads as data. The build extracts only these bytes and
the CHR graphics from the user's ROM (`src/rom_extract.rs`); the original's code isn't kept.
Addresses only, no ROM content.

    python3 tetris-rs/gen/rom_data.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "recomp", "gen"))
from gen import OPS, Program, parse_dbg  # noqa: E402

# Instructions whose opcode byte is read: `inc reset` / `inc initRam` write it back + 1 to
# reset the MMC1 (flow.rs, endgame.rs).
READ_OPCODES = ["reset", "initRam"]


def main():
    dbg_path = os.path.join(REPO, "disasm", "tetris.dbg")
    with open(os.path.join(REPO, "tetris.nes"), "rb") as f:
        prog = Program(f.read(), dbg_path)
    skip = set()
    for seg in parse_dbg(dbg_path)["seg"]:
        if seg["name"].startswith("unreferenced"):
            start = int(seg["start"], 16)
            skip.update(range(start, start + int(seg["size"], 16)))
    code = set()
    for a in prog.instr:
        code.update(range(a, a + OPS[prog.byte(a)][2]))
    names = {n: a for a, n in prog.labels.items()}
    for label in READ_OPCODES:
        code.discard(names[label])

    ranges = []
    for a in range(0x8000, 0x10000):
        if a in code or a in skip:
            continue
        if ranges and ranges[-1][0] + ranges[-1][1] == a:
            ranges[-1][1] += 1
        else:
            ranges.append([a, 1])
    kept = sum(n for _, n in ranges)

    out = [
        "//! PRG address ranges (start, length) extracted from the user's ROM: everything but the",
        "//! original's code and the data it never uses (generated by gen/rom_data.py). Addresses",
        "//! only, no ROM content.",
        "",
        f"/// {kept} of 32768 PRG bytes.",
        "pub const PRG_RANGES: &[(u16, u16)] = &[",
    ]
    out += [f"    (0x{a:04X}, {n})," for a, n in ranges]
    out.append("];")
    path = os.path.join(REPO, "tetris-rs", "src", "rom_data.rs")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(ranges)} ranges, {kept} of 32768 PRG bytes -> {os.path.relpath(path, REPO)}")


if __name__ == "__main__":
    main()
